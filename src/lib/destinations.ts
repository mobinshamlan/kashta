/** Great-circle distance in km. */
export function distanceKm(a: { lat: number; lon: number }, b: { lat: number; lon: number }): number {
  const R = 6371;
  const toRad = (d: number) => (d * Math.PI) / 180;
  const dLat = toRad(b.lat - a.lat);
  const dLon = toRad(b.lon - a.lon);
  const h =
    Math.sin(dLat / 2) ** 2 + Math.cos(toRad(a.lat)) * Math.cos(toRad(b.lat)) * Math.sin(dLon / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(h));
}

/**
 * Rough driving estimate from the chosen starting city: straight-line distance x 1.3 road factor
 * at 90 km/h average. Always labelled as an estimate in the UI; it is not a routed travel time.
 */
export function estimateDrive(d: { lat: number; lon: number }, city: CityId = "riyadh") {
  const km = distanceKm(ORIGINS[city], d);
  const roadKm = km * 1.3;
  const hours = roadKm / 90;
  return { straightKm: Math.round(km), roadKm: Math.round(roadKm), hours: Math.round(hours * 10) / 10 };
}
