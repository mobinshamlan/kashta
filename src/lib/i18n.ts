export function isLocale(v: unknown): v is Locale {
  return v === "ar" || v === "en";
}

/** Arabic counted nouns: 1 ساعة واحدة, 2 ساعتين, 3–10 ساعات, 11+ ساعة; fractions keep the singular. */
export function arHours(h: number): string {
  if (!Number.isInteger(h)) return `${h} ساعة`;
  if (h === 1) return "ساعة واحدة";
  if (h === 2) return "ساعتين";
  if (h <= 10) return `${h} ساعات`;
  return `${h} ساعة`;
}

export function arSites(n: number): string {
  if (n === 1) return "موقع واحد";
  if (n === 2) return "موقعين";
  if (n <= 10) return `${n} مواقع`;
  return `${n} موقعًا`;
}

/** Half-hour Saudi phrasing: 1.5 → "ساعة ونص", 2.5 → "ساعتين ونص". */
function arHalfHours(h: number): string {
  const whole = Math.floor(h);
  if (h === whole) return arHours(h);
  if (whole === 0) return "نص ساعة";
  return `${whole === 1 ? "ساعة" : whole === 2 ? "ساعتين" : `${whole} ساعات`} ونص`;
}

/** "حوالي ساعة ونص" / "~1.5 h": estimates are rounded to the half hour, never shown as precise. */
export function approxHours(h: number, locale: Locale): string {
  const r = Math.max(0.5, Math.round(h * 2) / 2);
  return locale === "ar" ? `حوالي ${arHalfHours(r)}` : `~${r} h`;
}

/** "7 من 10 ساعات" / "8 من 11 ساعة": the noun agrees with the total. */
export function arHoursOf(part: number, total: number): string {
  const p = Math.round(part), t = Math.round(total);
  return `${p} من ${t} ${t >= 3 && t <= 10 ? "ساعات" : "ساعة"}`;
}

/** Keeps a number with its unit in reading order inside Arabic text ("17°", "0%"). */
export const ltr = (s: string | number) => `\u2066${s}\u2069`;

/** List separator that matches the language. */
export function listJoin(items: string[], locale: Locale): string {
  return items.join(locale === "ar" ? "، " : ", ");
}

export const pick = (l: Localized, locale: Locale) => l[locale];

